// Helper to build sets with rep ranges and default rest
function makeSets(
  count: number,
  minReps: number,
  maxReps: number,
  targetWeightKg: number,
  restSeconds: number,
  isUnilateral = false
) {
  return Array.from({ length: count }, (_, i) => ({
    id: `set_${Math.random().toString(36).substring(2, 9)}_${i + 1}`,
    setNumber: i + 1,
    targetReps: minReps,
    minReps,
    maxReps,
    repsRange: `${minReps} a ${maxReps} reps`,
    targetWeightKg,
    restSeconds,
    completed: false,
    repsLeft: isUnilateral ? minReps : undefined,
    repsRight: isUnilateral ? minReps : undefined,
  }));
}

